  static int get totalCount => allExercises.length;

  /// Instant query filter by muscle group, equipment type, and text search
  static List<Exercise> filter({
    MuscleGroup? muscleGroup,
    EquipmentType? equipment,
    ExerciseMechanic? mechanic,
    String query = '',
  }) {
    final cleanQuery = query.trim().toLowerCase();

    return allExercises.where((ex) {
      if (muscleGroup != null && ex.muscleGroup != muscleGroup) {
        return false;
      }
      if (equipment != null && ex.equipment != equipment) {
        return false;
      }
      if (mechanic != null && ex.mechanic != mechanic) {
        return false;
      }
      if (cleanQuery.isNotEmpty) {
        final matchName = ex.name.toLowerCase().contains(cleanQuery);
        final matchDesc = ex.description.toLowerCase().contains(cleanQuery);
        final matchSecondary = ex.secondaryMuscles
            .any((s) => s.toLowerCase().contains(cleanQuery));
        if (!matchName && !matchDesc && !matchSecondary) {
          return false;
        }
      }
      return true;
    }).toList();
  }
